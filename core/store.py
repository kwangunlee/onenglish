# ── 학습 목표 ────────────────────────────────────────────────────
# 반이나 학생에게 기간(start_on~end_on)을 정해 겁니다. 주제·핵심 단어·표현·과제.
# 대화마다 결과(goal_results)를 한 줄씩 남깁니다 (대화 id 가 열쇠라 덮어쓰기 가능).
# 판단 로직(어떤 목표가 지금 걸려 있나, 달성했나)은 core/goals.py 에 있습니다.

GOAL_FIELDS = ("target_type", "target_id", "start_on", "end_on", "topic", "words",
               "expressions", "task", "min_words", "memo")


def _goal_row(row: dict) -> dict:
    row = dict(row)
    for key in ("words", "expressions"):
        value = row.get(key)
        row[key] = json.loads(value) if isinstance(value, str) else list(value or [])
    return row


def _check_goal(fields: dict) -> dict:
    """빈 값 정리와 기본 검사. 두 저장소가 같은 규칙을 쓰도록 여기 한 곳에 둡니다."""
    out = dict(fields)
    if out.get("target_type") not in ("class", "profile"):
        raise ValueError("목표 대상은 반 또는 학생이어야 해요.")
    if out.get("target_id") in (None, ""):
        raise ValueError("목표를 걸 반이나 학생을 골라 주세요.")
    out["target_id"] = int(out["target_id"])
    out["topic"] = (out.get("topic") or "").strip()
    if not out["topic"]:
        raise ValueError("주제를 입력해 주세요.")
    out["words"] = [w.strip() for w in (out.get("words") or []) if w and w.strip()]
    out["expressions"] = [e.strip() for e in (out.get("expressions") or []) if e and e.strip()]
    out["task"] = (out.get("task") or "").strip() or None
    out["memo"] = (out.get("memo") or "").strip() or None
    start, end = str(out.get("start_on") or today())[:10], str(out.get("end_on") or "")[:10]
    out["start_on"], out["end_on"] = start, (end or start)
    if out["end_on"] < out["start_on"]:
        raise ValueError("끝나는 날이 시작하는 날보다 빨라요.")
    mw = out.get("min_words")
    out["min_words"] = None if mw in (None, "", 0) else max(1, min(int(mw), len(out["words"]) or 1))
    return out


