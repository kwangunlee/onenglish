def _result_row(row: dict) -> dict:
    row = dict(row)
    for key in ("words_used", "words_heard"):
        value = row.get(key)
        row[key] = json.loads(value) if isinstance(value, str) else list(value or [])
    row["achieved"] = bool(row.get("achieved"))
    td = row.get("task_done")
    row["task_done"] = None if td is None else bool(td)
    return row


def save_goal_result(session_id: str, goal_id, profile_id: int, words_used: list,
                     words_heard: list, task_done, achieved: bool,
                     note: str | None = None) -> None:
    """대화 하나의 목표 결과를 저장합니다. 같은 대화면 덮어씁니다(대화 중 갱신)."""
    values = (session_id, int(goal_id), int(profile_id),
              json.dumps(list(words_used), ensure_ascii=False),
              json.dumps(list(words_heard), ensure_ascii=False),
              None if task_done is None else int(bool(task_done)),
              int(bool(achieved)), note, now())
    with connect() as conn:
        conn.execute(
            "INSERT INTO goal_results (session_id, goal_id, profile_id, words_used,"
            " words_heard, task_done, achieved, note, updated_at)"
            " VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)"
            " ON CONFLICT(session_id) DO UPDATE SET goal_id = excluded.goal_id,"
            " profile_id = excluded.profile_id, words_used = excluded.words_used,"
            " words_heard = excluded.words_heard, task_done = excluded.task_done,"
            " achieved = excluded.achieved, note = excluded.note,"
            " updated_at = excluded.updated_at",
            values,
        )


